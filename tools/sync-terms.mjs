// Copies the Terms of Service from the zome repo into this app, for /terms:
//   node tools/sync-terms.mjs ../zome/TERMS-OF-SERVICE.md
import { readFileSync, writeFileSync } from 'node:fs'
const from = process.argv[2] ?? '../zome/TERMS-OF-SERVICE.md'
const text = readFileSync(from, 'utf8')
writeFileSync(new URL('../lib/terms-text.ts', import.meta.url),
  `// Generated by tools/sync-terms.mjs from the zome repo's TERMS-OF-SERVICE.md. Don't edit by hand.\nexport const TERMS = ${JSON.stringify(text)}\n`)
console.log('lib/terms-text.ts written,', text.length, 'characters')
