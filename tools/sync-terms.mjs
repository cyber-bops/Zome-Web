// Copies the Terms of Service and the Privacy Policy from the zome repo into
// this app, for /terms and /privacy:
//   node tools/sync-terms.mjs ../zome
import { readFileSync, writeFileSync } from 'node:fs'

const repo = process.argv[2] ?? '../zome'
const docs = [
  ['TERMS-OF-SERVICE.md', 'terms-text.ts', 'TERMS'],
  ['PRIVACY-POLICY.md', 'privacy-text.ts', 'PRIVACY'],
]
for (const [file, out, name] of docs) {
  const text = readFileSync(`${repo}/${file}`, 'utf8')
  const body = `// Generated by tools/sync-terms.mjs from the zome repo's ${file}. Don't edit by hand.\n` +
    `export const ${name} = ${JSON.stringify(text)}\n`
  writeFileSync(new URL(`../lib/${out}`, import.meta.url), body)
  console.log(`lib/${out} written,`, text.length, 'characters')
}
